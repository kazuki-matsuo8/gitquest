## メッセージ以外も直せる

ファイルの追加忘れにも使えます。

```bash
git add 忘れてたファイル.txt
git commit --amend --no-edit    # メッセージはそのまま
```

## 注意点

amend は「修正」ではなく **「コミットの作り直し」** です。コミットのハッシュ値が変わります。

```
修正前: a1b2c3d "initial commt"
修正後: e4f5g6h "initial commit"   ← 別のコミットになる
```

そのため、**すでに push したコミットを amend してはいけません**。チームメンバーの履歴と食い違ってしまいます。「push する前なら自由に直してよい」と覚えましょう。

## 確認方法

```bash
git log --oneline    # メッセージが直っているか確認
