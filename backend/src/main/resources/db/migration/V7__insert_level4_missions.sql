 '# コンフリクト（競合）とは？

2 つのブランチが **同じファイルの同じ行** を別々に変更していた場合、Git はどちらを採用すべきか判断できません。これが **コンフリクト（競合）** です。

## コンフリクトが起きるとどうなる？

`git merge` を実行すると、こんなメッセージが表示されます。

```
Auto-merging README.md
CONFLICT (content): Merge conflict in README.md
Automatic merge failed; fix conflicts and then commit the result.
```

ファイルの中身を見ると、Git が競合箇所に **マーカー** を入れています。

```
<<<<<<< HEAD
main ブランチでの変更内容
=======
feature ブランチでの変更内容
>>>>>>> feature
```

| マーカー | 意味 |
|---------|------|
| `<<<<<<< HEAD` 〜 `=======` | 今いるブランチ (main) の内容 |
| `=======` 〜 `>>>>>>> feature` | マージしようとしたブランチの内容 |

## 解決の手順

1. コンフリクトしたファイルを開く（`cat README.md` で確認できる）
2. マーカーを消して、残したい内容に書き換える
3. `git add .` で解決済みであることを Git に伝える
4. `git commit` でマージを完了する

