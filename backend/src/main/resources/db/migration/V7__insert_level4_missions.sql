 '# コミットを取り消す 2 つの方法

問題のあるコミットをしてしまったとき、取り消す方法は 2 つあります。

## revert と reset の違い

```
revert: 打ち消すコミットを「追加」する（履歴が残る）
●───●───●───●
        bad  「bad を打ち消す」コミット

reset: 履歴ごと「なかったこと」にする（履歴が消える）
●───●───✕
        bad が消える
```

| | git revert | git reset |
|--|-----------|-----------|
| 履歴 | 残る | 消える |
| 安全性 | 高い | 低い（操作ミスで作業が消えることも） |
| push 済みでも使える | ○ | ✕（チームに迷惑がかかる） |

## git revert の使い方

```bash
git revert HEAD            # 直前のコミットを打ち消す
git revert コミットハッシュ  # 特定のコミットを打ち消す
```

実行するとエディタが開いて、打ち消しコミットのメッセージを編集できます。そのまま保存して閉じれば OK です（vim なら `:wq`）。

エディタを開きたくない場合は:

```bash
git revert HEAD --no-edit
```

## どちらを使うべき？

- **共有済み（push 済み）のコミット** → 必ず revert
- **ローカルだけのコミット** → どちらでも OK

迷ったら revert を使えば安全です。チーム開発では「履歴は消さない」が原則です。');
